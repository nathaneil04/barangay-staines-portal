// Pre-index for fast search
const SEARCH_MAP = SEARCH_INDEX.map(item => ({
  ...item,
  _searchText: (item.title + " " + item.h1 + " " + item.text + " " + 
    item.ordinances.map(o => o.number + " " + o.name + " " + o.desc).join(" ") + " " +
    item.benefits.map(b => b.name + " " + b.agency + " " + b.desc).join(" ")
  ).toLowerCase()
}));

let searchDebounceTimer;

function debouncedSearch() {
  clearTimeout(searchDebounceTimer);
  searchDebounceTimer = setTimeout(performSearch, 150);
}

function performSearch() {
  const query = document.getElementById('globalSearch').value.trim().toLowerCase();
  const resultsContainer = document.getElementById('searchResultsContainer');
  const resultsModal = document.getElementById('searchResultsModal');
  
  // Filter local cards first
  const cards = document.querySelectorAll('#servicesGrid .sf-card');
  cards.forEach(card => {
    const title = card.getAttribute('data-title').toLowerCase();
    const text = card.textContent.toLowerCase();
    const match = !query || title.includes(query) || text.includes(query);
    card.style.display = match ? 'flex' : 'none';
  });
  
  if (!query) {
    resultsModal.classList.remove('active');
    return;
  }
  
  // Search across all pages
  const results = [];
  SEARCH_MAP.forEach(item => {
    if (item._searchText.includes(query)) {
      // Find matching sections
      const matches = [];
      
      // Check ordinances
      item.ordinances.forEach(ord => {
        const ordText = (ord.number + " " + ord.name + " " + ord.desc).toLowerCase();
        if (ordText.includes(query)) {
          matches.push({
            type: 'ordinance',
            title: 'Ordinance No. ' + ord.number,
            subtitle: ord.name,
            desc: ord.desc,
            file: item.file
          });
        }
      });
      
      // Check benefits
      item.benefits.forEach(ben => {
        const benText = (ben.name + " " + ben.agency + " " + ben.desc).toLowerCase();
        if (benText.includes(query)) {
          matches.push({
            type: 'benefit',
            title: ben.name,
            subtitle: ben.agency,
            desc: ben.desc,
            file: item.file
          });
        }
      });
      
      // Check general content
      if (item._searchText.includes(query) && matches.length === 0) {
        matches.push({
          type: 'page',
          title: item.h1 || item.title,
          subtitle: item.file,
          desc: item.text.substring(0, 150) + '...',
          file: item.file
        });
      }
      
      results.push(...matches);
    }
  });
  
  renderSearchResults(query, results);
}

function renderSearchResults(query, results) {
  const container = document.getElementById('searchResultsContainer');
  const badge = document.getElementById('searchQueryBadge');
  const modal = document.getElementById('searchResultsModal');
  
  badge.textContent = results.length + ' Found';
  
  if (results.length === 0) {
    container.innerHTML = '<div class="search-no-results"><p>No results found for "' + escapeHtml(query) + '"</p><p>Try searching for: clearance, indigency, ordinance, benefits, health, business, disaster, youth, environmental, curfew</p></div>';
    modal.classList.add('active');
    return;
  }
  
  let html = '<div class="search-results-list">';
  results.forEach(result => {
    const icon = result.type === 'ordinance' ? '📜' : result.type === 'benefit' ? '👤' : '📄';
    html += '<a href="' + result.file + '" class="search-result-item">';
    html += '<div class="search-result-icon">' + icon + '</div>';
    html += '<div class="search-result-content">';
    html += '<div class="search-result-title">' + escapeHtml(result.title) + '</div>';
    html += '<div class="search-result-subtitle">' + escapeHtml(result.subtitle) + '</div>';
    html += '<div class="search-result-desc">' + escapeHtml(result.desc) + '</div>';
    html += '</div></a>';
  });
  html += '</div>';
  
  container.innerHTML = html;
  modal.classList.add('active');
}

function escapeHtml(text) {
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}

function closeSearchModal() {
  document.getElementById('searchResultsModal').classList.remove('active');
}

// Close modal on escape key
document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') {
    closeSearchModal();
  }
});

// Replace old filterServices with debounced search
if (document.getElementById('globalSearch')) {
  document.getElementById('globalSearch').addEventListener('input', debouncedSearch);
  document.getElementById('globalSearch').addEventListener('keyup', function(e) {
    if (e.key === 'Enter') performSearch();
  });
}
